import { describe, it, expect } from 'vitest';
import { resolveDisplay, resolveServerCrop } from '../../src/export/exporter';
import { buildCloudimageUrlFromDescriptor, type CropDescriptor } from '../../src/export/cloudimage-url';
import { createInitialState } from '../../src/transforms/transform-state';
import type { TransformState } from '../../src/core/types';

/**
 * Back-compat with descriptors saved by the published 3.0.0. Their state has NO
 * `turnedBox` key, and they must keep producing the crop 3.0.0 produced:
 * - an odd quarter turn letterboxed the photo (shrunk to the box's short axis);
 * - flip mirrored about the crop-frame centre, not the photo centre.
 *
 * Expected values below were generated by running the real v3.0.0 sources
 * (`git archive v3.0.0 src`) on these exact states — not re-derived by hand.
 * (Turned + TILTED crops are intentionally excluded: de49653, after 3.0.0,
 * fixed a wrong outer-crop placement there, so 3.0.0's output was a bug.)
 */

const IW = 1920;
const IH = 1080;
const CW = 800;
const CH = 450;

// Exactly the shape 3.0.0 serialized — no turnedBox key.
function legacy(s: Omit<TransformState, 'turnedBox'>): TransformState {
  return s as TransformState;
}

function url(state: TransformState): string {
  const d: CropDescriptor = {
    state,
    imageWidth: IW,
    imageHeight: IH,
    containerWidth: CW,
    containerHeight: CH,
    variant: 'classic',
  };
  return buildCloudimageUrlFromDescriptor(d, { src: 'https://doc.cloudimg.io/sample.jpg' });
}

describe('legacy (3.0.0) descriptors render exactly as 3.0.0', () => {
  it('90° turn → letterboxed photo, same crop and URL', () => {
    const s = legacy({
      quarterTurns: -90, rotation: 0, flipH: false, flipV: false, scale: 1, panX: 0, panY: 0,
      cropRect: { x: 0.4, y: 0.4, width: 0.2, height: 0.2 },
    });
    const d = resolveDisplay(s, IW, IH, CW, CH, 'classic');
    expect(d.drawW).toBeCloseTo(1080);
    expect(d.drawH).toBeCloseTo(607.5);
    const sc = resolveServerCrop(s, IW, IH, CW, CH, 'classic');
    expect(sc.cropPx).toEqual({ x: 768, y: 199, width: 384, height: 682 });
    expect(sc.clamped).toBe(false);
    expect(url(s)).toBe('https://doc.cloudimg.io/sample.jpg?r=90&tl_px=768,199&br_px=1152,881');
  });

  it('flip with an off-centre frame → mirrored about the crop centre', () => {
    const s = legacy({
      quarterTurns: 0, rotation: 0, flipH: true, flipV: false, scale: 1, panX: 0, panY: 0,
      cropRect: { x: 0.05, y: 0.3, width: 0.4, height: 0.5 },
    });
    expect(resolveServerCrop(s, IW, IH, CW, CH, 'classic').cropPx).toEqual({ x: 96, y: 324, width: 768, height: 540 });
    expect(url(s)).toBe('https://doc.cloudimg.io/sample.jpg?flip=h&tl_px=96,324&br_px=864,864');
  });

  it('270° turn + flip both axes + zoom + pan', () => {
    const s = legacy({
      quarterTurns: -270, rotation: 0, flipH: true, flipV: true, scale: 1.6, panX: 40, panY: -25,
      cropRect: { x: 0.05, y: 0.3, width: 0.4, height: 0.5 },
    });
    const sc = resolveServerCrop(s, IW, IH, CW, CH, 'classic');
    expect(sc.cropPx).toEqual({ x: 827, y: 817, width: 600, height: 263 });
    expect(sc.clamped).toBe(true);
    expect(url(s)).toBe('https://doc.cloudimg.io/sample.jpg?flip=hv&r=270&tl_px=827,817&br_px=1427,1080');
  });

  it('a state from this version (explicit turnedBox) uses the current layout, not the legacy one', () => {
    const fresh = createInitialState();
    expect(fresh.turnedBox).toBe(false);
    // Same off-centre flip as above, but current model: mirrored about the photo centre.
    const s: TransformState = {
      ...fresh,
      flipH: true,
      cropRect: { x: 0.05, y: 0.3, width: 0.4, height: 0.5 },
    };
    expect(resolveServerCrop(s, IW, IH, CW, CH, 'classic').cropPx).not.toEqual({ x: 96, y: 324, width: 768, height: 540 });
  });
});
